// Liste des véhicules autorisés : import du concessionnaire, Paragon et deux-roues exclus, recherche et filtres.
import { readFileSync } from "node:fs";
import { launch, BASE, SHOT, check, newPage, text } from "./lib.mjs";
const data = JSON.parse(readFileSync(new URL("../../data/vehicles.json", import.meta.url), "utf8")).vehicles;
check("import : aucun Paragon dans la liste", !data.some((v) => /paragon/i.test(`${v.name} ${v.model}`)));
check("import : aucun deux-roues dans la liste", !data.some((v) => /\b(moto|bike|scooter|quad)\b/i.test(`${v.name} ${v.model} ${v.category}`) || v.seats === 1));
check("import : aucune super sportive (catégorie interdite)", !data.some((v) => /super/i.test(v.category)));
check("import : plus de 300 véhicules, sans doublon", data.length > 300 && new Set(data.map((v) => `${v.brand}|${v.model}`)).size === data.length, String(data.length));
const b = await launch();
const p = await newPage(b, { width: 1280, height: 900 });
await p.goto(BASE + "/vehicles"); await p.waitForLoadState("networkidle"); await p.waitForTimeout(3500);
const total = await p.locator(".veh-card").count();
check("la page affiche toute la liste", total === data.length, `${total}/${data.length}`);
check("aucun mot du jeu ou du serveur sur la page", !/\bgta\b|fivem|rp\b|storylife|pdm|concessionnaire/i.test(await text(p)));
await p.screenshot({ path: `${SHOT}/400-vehicules-liste.png`, fullPage: false });
{
  // miniatures : servies par ce site (jamais depuis un site tiers), chargées, et sans adresse d'origine dans la page
  const html = await p.content();
  check("aucune adresse d'image tierce dans la page", !/wikia|gtabase|bing\.net|sportskeeda|pinimg|gtacars/i.test(html));
  const first = p.locator(".veh-card .veh-img").first();
  await first.scrollIntoViewIfNeeded(); await p.waitForTimeout(1500);
  const info = await first.evaluate((i) => ({ src: i.getAttribute("src"), ok: i.complete && i.naturalWidth > 0 }));
  check("miniature chargée depuis /api/vehicle-img/…", /^\/api\/vehicle-img\/[a-z0-9-]+$/.test(info.src ?? "") && info.ok, JSON.stringify(info));
  const r1 = await p.request.get(BASE + "/api/vehicle-img/inconnu-xyz"), r2 = await p.request.get(BASE + "/api/vehicle-img/..%2f..%2fetc");
  check("identifiant inconnu ou piégé : 404", r1.status() === 404 && r2.status() === 404, `${r1.status()} ${r2.status()}`);
  const ok = await p.request.get(BASE + "/api/vehicle-img/" + data[0].slug);
  check("miniature WebP mise en cache longue durée", ok.status() === 200 && /image\/webp/.test(ok.headers()["content-type"]) && /immutable/.test(ok.headers()["cache-control"]), `${ok.status()} ${ok.headers()["cache-control"]}`);
}
await p.fill("input[type=search]", "blista");
check("recherche instantanée (sans accent ni casse)", (await p.locator(".veh-card").count()) >= 1 && /Blista/i.test(await p.locator(".veh-card").first().innerText()));
// tri par puissance, filtre par marque, présentation compacte, fiche détaillée
await p.fill("input[type=search]", "");
await p.selectOption("select[aria-label='Trier']", "hp-desc");
const maxHp = Math.max(...data.map((v) => v.hp ?? 0));
check("tri par puissance décroissante", (await p.locator(".veh-card").first().innerText()).includes(String(maxHp)), await p.locator(".veh-card").first().innerText().then((t) => t.replace(/\n/g, " ")));
await p.selectOption("select[aria-label='Trier']", "az");
const brand = data[0].brand;
await p.selectOption("select[aria-label='Marque']", brand);
check("filtre par marque", (await p.locator(".veh-card").count()) === data.filter((v) => v.brand === brand).length);
await p.selectOption("select[aria-label='Marque']", "*");
await p.locator("button[aria-label='Liste compacte']").click();
check("présentation compacte : barres de puissance masquées", (await p.locator(".veh-card-row").count()) === data.length && (await p.locator(".veh-card .veh-bar").count()) === 0);
await p.locator("button[aria-label='Cartes']").click();
await p.locator(".veh-card").first().click();
await p.waitForTimeout(500);
const open = await p.locator("dialog.veh-dialog[open]").count();
const dt = open ? await p.locator("dialog.veh-dialog").innerText() : "";
check("clic : fiche détaillée (puissance, places, boîte, carburant, autorisé)", open === 1 && /PUISSANCE/i.test(dt) && /PLACES/i.test(dt) && /AUTORIS/i.test(dt) && /BO[IÎ]TE/i.test(dt), dt.replace(/\n+/g, " ").slice(0, 160));
await p.screenshot({ path: `${SHOT}/405-vehicule-fiche.png`, fullPage: false });
await p.keyboard.press("Escape"); await p.waitForTimeout(300);
check("Échap ferme la fiche", (await p.locator("dialog.veh-dialog[open]").count()) === 0);
await p.fill("input[type=search]", "xyzxyz");
check("recherche sans résultat : message", /Aucun véhicule/i.test(await text(p)));
await p.fill("input[type=search]", "");
await p.locator(".shop-chip", { hasText: /^SUV$/i }).click();
const suv = await p.locator(".veh-card").count();
check("filtre par catégorie", suv === data.filter((v) => v.category === "SUV").length && suv > 0, String(suv));
await p.screenshot({ path: `${SHOT}/401-vehicules-suv.png`, fullPage: false });
await p.goto(BASE + "/vehicles"); await p.waitForLoadState("networkidle");
await p.locator('button[aria-label="English"]:visible').first().click(); await p.waitForTimeout(1500);
check("version anglaise", /ALLOWED/i.test(await text(p)) && !/Véhicules autorisés/.test(await text(p)));
const m = await newPage(b, { width: 390, height: 800 });
await m.goto(BASE + "/vehicles"); await m.waitForLoadState("networkidle"); await m.waitForTimeout(3500);
check("téléphone : pas de débordement horizontal", await m.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1));
await m.screenshot({ path: `${SHOT}/402-vehicules-mobile.png`, fullPage: false });
check("aucune erreur JavaScript", !(p.errors ?? []).length && !(m.errors ?? []).length);
for (const [path, what] of [["/rules", "règlement"], ["/register", "inscription"]]) {
  await p.goto(BASE + path); await p.waitForLoadState("networkidle");
  check(`lien vers la liste dans la page ${what}`, (await p.locator("a[data-veh-link][href='/vehicles']").count()) === 1);
}
await p.goto(BASE + "/"); await p.waitForLoadState("networkidle");
check("menu : pas d'entrée « VÉHICULES »", (await p.locator("a[href='/vehicles']").count()) === 0);
await p.locator(`button[aria-label="Français"]:visible`).first().click().catch(() => {}); await p.goto(BASE + "/rules"); await p.waitForLoadState("networkidle"); await p.waitForTimeout(3500);
const card = p.locator("a.rules-card[href='/vehicles']");
check("règlement : carré cliquable vers la liste", (await card.count()) === 1 && /(Liste des véhicules autorisés|List of allowed vehicles)/i.test(await card.innerText()) && /\b341\b/.test(await card.innerText()));
await card.scrollIntoViewIfNeeded(); await p.screenshot({ path: `${SHOT}/403-reglement-carre.png`, fullPage: false });
await card.click(); await p.waitForURL(/\/vehicles$/, { timeout: 10000 }).catch(() => {});
check("le carré ouvre la liste", /\/vehicles$/.test(p.url()), p.url());
await p.goto(BASE + "/register"); await p.waitForLoadState("networkidle"); await p.waitForTimeout(3500);
const sc = p.locator("a[data-veh-shortcut][href='/vehicles']");
check("inscription : raccourci vers la liste dans le panneau de droite", (await sc.count()) === 1 && (await sc.getAttribute("target")) === "_blank" && /\b341\b/.test(await sc.innerText()));
await p.screenshot({ path: `${SHOT}/404-inscription-raccourci.png`, fullPage: false });
const [popup] = await Promise.all([p.context().waitForEvent("page"), sc.click()]);
await popup.waitForLoadState("networkidle");
check("le raccourci ouvre la liste dans un nouvel onglet (le formulaire reste intact)", /\/vehicles$/.test(popup.url()) && /\/register/.test(p.url()), popup.url());
await b.close();
